import React, { useState, useEffect } from 'react';
import { useSearchParams, useNavigate } from 'react-router-dom';
import { api } from '../api/client';
import {
  FileText,
  Calendar,
  Clock,
  Video,
  CheckSquare,
  Square,
  HelpCircle,
  Award,
  Sparkles,
  ArrowLeft
} from 'lucide-react';

export default function MeetingPreparation() {
  const [searchParams] = useSearchParams();
  const navigate = useNavigate();
  const bookingId = searchParams.get('booking_id');

  const [bookings, setBookings] = useState([]);
  const [selectedBookingId, setSelectedBookingId] = useState(bookingId || '');
  const [brief, setBrief] = useState(null);
  const [checkedItems, setCheckedItems] = useState({});
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    loadSessions();
  }, []);

  useEffect(() => {
    if (selectedBookingId) {
      loadBrief(selectedBookingId);
    }
  }, [selectedBookingId]);

  const loadSessions = async () => {
    try {
      const data = await api.getBookings();
      setBookings(data || []);
      if (!selectedBookingId && data && data.length > 0) {
        setSelectedBookingId(data[0].id);
      }
    } catch (e) {
      console.error(e);
    }
  };

  const loadBrief = async (bId) => {
    setLoading(true);
    setError(null);
    try {
      const briefData = await api.getBookingBrief(bId);
      setBrief(briefData);
    } catch (err) {
      setError(err.message || 'Brief not available for this session.');
      setBrief(null);
    } finally {
      setLoading(false);
    }
  };

  const toggleCheck = (index) => {
    setCheckedItems((prev) => ({
      ...prev,
      [index]: !prev[index],
    }));
  };

  return (
    <div className="max-w-5xl mx-auto px-6 lg:px-10 py-12 space-y-8">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-6 pb-6 border-b border-zinc-200/80">
        <div className="space-y-1">
          <button
            onClick={() => navigate('/sessions')}
            className="text-xs text-zinc-500 hover:text-zinc-900 flex items-center space-x-1.5 mb-1.5 font-medium transition"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            <span>Back to Sessions</span>
          </button>
          <h1 className="text-2xl sm:text-3xl font-heading font-bold text-zinc-900 tracking-tight">
            Pre-Call Preparation Brief
          </h1>
          <p className="text-xs sm:text-sm text-zinc-500">
            Personalized agenda, 3 key discussion questions, and preparation checklist generated by Gemini.
          </p>
        </div>

        {bookings.length > 1 && (
          <div className="flex items-center space-x-2 text-xs">
            <span className="text-zinc-500 font-medium">Session:</span>
            <select
              value={selectedBookingId}
              onChange={(e) => setSelectedBookingId(e.target.value)}
              className="px-3.5 py-2 bg-white border border-zinc-300 rounded-xl text-zinc-800 font-semibold focus:ring-2 focus:ring-zinc-900"
            >
              {bookings.map((b) => (
                <option key={b.id} value={b.id}>
                  {b.mentor_name} ({new Date(b.scheduled_at).toLocaleDateString([], { month: 'short', day: 'numeric' })})
                </option>
              ))}
            </select>
          </div>
        )}
      </div>

      {loading ? (
        <div className="py-20 text-center text-zinc-500 text-sm">
          Loading preparation brief...
        </div>
      ) : error ? (
        <div className="p-10 text-center bg-white rounded-3xl border border-zinc-200/90 space-y-3">
          <p className="text-base font-semibold text-zinc-900">{error}</p>
          <p className="text-xs sm:text-sm text-zinc-500">Select an active session from the menu or book a new one.</p>
        </div>
      ) : brief ? (
        <div className="space-y-8">
          {/* Metadata Card */}
          <div className="bg-white rounded-3xl border border-zinc-200/90 p-7 sm:p-8 shadow-card flex flex-col sm:flex-row items-start sm:items-center justify-between gap-6">
            <div className="space-y-1.5">
              <span className="text-[10px] font-semibold text-emerald-800 uppercase tracking-wider bg-emerald-50 px-2.5 py-1 rounded-full border border-emerald-200/60">
                Authoritative Saved Brief
              </span>
              <h2 className="text-xl font-heading font-bold text-zinc-900">
                Mentorship with {brief.mentor_name}
              </h2>
              <p className="text-xs sm:text-sm text-zinc-600">
                Domain: <strong className="text-zinc-800">{brief.mentor_domain}</strong>
              </p>
              <div className="flex items-center space-x-4 text-xs text-zinc-600 pt-1 font-medium">
                <span className="flex items-center space-x-1.5">
                  <Calendar className="w-4 h-4 text-zinc-400" />
                  <span>{new Date(brief.meeting_scheduled_at).toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' })}</span>
                </span>
                <span>•</span>
                <span>45 Minutes</span>
              </div>
            </div>

            {brief.meet_link && (
              <a
                href={brief.meet_link}
                target="_blank"
                rel="noopener noreferrer"
                className="px-6 py-3 bg-emerald-700 hover:bg-emerald-800 text-white rounded-2xl text-xs sm:text-sm font-semibold flex items-center space-x-2 transition shadow-sm"
              >
                <Video className="w-4 h-4" />
                <span>Join Google Meet</span>
              </a>
            )}
          </div>

          {/* Context & Blocker */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
            <div className="bg-white rounded-3xl border border-zinc-200/90 p-7 shadow-card space-y-2">
              <h3 className="text-xs font-semibold uppercase tracking-wider text-zinc-500">
                Student Context Summary
              </h3>
              <p className="text-xs sm:text-sm text-zinc-700 leading-relaxed">
                {brief.student_context_summary}
              </p>
            </div>

            <div className="bg-white rounded-3xl border border-zinc-200/90 p-7 shadow-card space-y-2">
              <h3 className="text-xs font-semibold uppercase tracking-wider text-zinc-500">
                Immediate Career Blocker
              </h3>
              <p className="text-xs sm:text-sm text-zinc-900 font-semibold leading-relaxed">
                {brief.current_blocker}
              </p>
            </div>
          </div>

          {/* 3 Discussion Questions */}
          <div className="bg-white rounded-3xl border border-zinc-200/90 p-7 sm:p-8 shadow-card space-y-5">
            <div className="flex items-center justify-between pb-3 border-b border-zinc-100">
              <h3 className="text-base font-heading font-bold text-zinc-900 flex items-center space-x-2">
                <HelpCircle className="w-4 h-4 text-emerald-700" />
                <span>Three Concrete Discussion Questions</span>
              </h3>
              <span className="text-xs text-zinc-600 font-medium">Tailored to Mentor's Domain</span>
            </div>

            <div className="space-y-3.5">
              {brief.key_questions_to_cover?.map((q, idx) => (
                <div
                  key={idx}
                  className="flex items-start space-x-3.5 p-4 bg-zinc-50/70 rounded-2xl border border-zinc-200/80"
                >
                  <span className="w-6 h-6 rounded-lg bg-zinc-900 text-white font-bold text-xs flex items-center justify-center flex-shrink-0 mt-0.5">
                    {idx + 1}
                  </span>
                  <p className="text-xs sm:text-sm text-zinc-800 leading-relaxed font-medium">{q}</p>
                </div>
              ))}
            </div>
          </div>

          {/* Suggested Agenda & Prep */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
            <div className="bg-white rounded-3xl border border-zinc-200/90 p-7 shadow-card space-y-4">
              <h3 className="text-sm font-heading font-bold text-zinc-900 flex items-center space-x-2">
                <Clock className="w-4 h-4 text-zinc-600" />
                <span>Suggested 45-Minute Agenda</span>
              </h3>
              <div className="space-y-2.5">
                {brief.suggested_agenda?.map((ag, i) => (
                  <div key={i} className="text-xs sm:text-sm text-zinc-700 p-3 bg-zinc-50 rounded-xl border border-zinc-200/70">
                    {ag}
                  </div>
                ))}
              </div>
            </div>

            <div className="bg-white rounded-3xl border border-zinc-200/90 p-7 shadow-card space-y-5">
              <div className="space-y-2">
                <h3 className="text-xs font-semibold uppercase tracking-wider text-zinc-500">
                  Recommended Preparation
                </h3>
                <p className="text-xs sm:text-sm text-zinc-700 leading-relaxed">
                  {brief.recommended_preparation}
                </p>
              </div>

              <div className="space-y-2 pt-3 border-t border-zinc-100">
                <h3 className="text-xs font-semibold uppercase tracking-wider text-emerald-800 flex items-center space-x-1.5">
                  <Award className="w-4 h-4 text-emerald-700" />
                  <span>Desired Outcome</span>
                </h3>
                <p className="text-xs sm:text-sm text-zinc-900 font-semibold leading-relaxed">
                  {brief.desired_outcome}
                </p>
              </div>
            </div>
          </div>

          {/* Checklist */}
          {brief.checklist && brief.checklist.length > 0 && (
            <div className="bg-white rounded-3xl border border-zinc-200/90 p-7 sm:p-8 shadow-card space-y-4">
              <h3 className="text-base font-heading font-bold text-zinc-900 flex items-center space-x-2">
                <CheckSquare className="w-4 h-4 text-emerald-700" />
                <span>Pre-Meeting Checklist</span>
              </h3>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                {brief.checklist.map((item, idx) => {
                  const checked = checkedItems[idx] || false;
                  return (
                    <button
                      key={idx}
                      type="button"
                      onClick={() => toggleCheck(idx)}
                      className={`flex items-start space-x-3 p-3.5 rounded-2xl border text-left transition ${
                        checked ? 'bg-zinc-50 border-zinc-200 text-zinc-400' : 'bg-white border-zinc-200/90 text-zinc-800 hover:bg-zinc-50'
                      }`}
                    >
                      <div className="mt-0.5">
                        {checked ? (
                          <CheckSquare className="w-4 h-4 text-emerald-700" />
                        ) : (
                          <Square className="w-4 h-4 text-zinc-300" />
                        )}
                      </div>
                      <span className={`text-xs sm:text-sm font-medium ${checked ? 'line-through text-zinc-600' : ''}`}>
                        {item}
                      </span>
                    </button>
                  );
                })}
              </div>
            </div>
          )}
        </div>
      ) : null}
    </div>
  );
}
